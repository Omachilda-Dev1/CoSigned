/**
 * copy-abis.js
 *
 * Copies compiled ABIs from Hardhat artifacts into the frontend as a typed
 * TypeScript module (`as const`), so wagmi/viem can infer argument and return
 * types for every contract call.
 *
 * Usage: npm run compile && npm run copy-abis
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "frontend", "lib", "abi.ts");

const CONTRACTS = [
  { name: "cosignedAbi", artifact: "artifacts/contracts/CoSigned.sol/CoSigned.json" },
  { name: "cosignedNftAbi", artifact: "artifacts/contracts/CoSignedNFT.sol/CoSignedNFT.json" },
];

let out =
  "// AUTO-GENERATED by scripts/copy-abis.js — do not edit by hand.\n" +
  "// Re-run `npm run copy-abis` from the repo root after recompiling contracts.\n\n";

for (const { name, artifact } of CONTRACTS) {
  const src = path.join(ROOT, artifact);
  if (!fs.existsSync(src)) {
    console.error(`✗ Not found: ${artifact} — run \`npm run compile\` first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(fs.readFileSync(src, "utf8"));
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  console.log(`✓ ${name} ← ${artifact}`);
}

fs.writeFileSync(OUT, out.trimEnd() + "\n");
console.log(`\nWrote ${path.relative(ROOT, OUT)}`);
